// Regenerates public/regions/<CC>.json (address State/Province and City dropdowns, owner 2026-10-19).
// Source: the repository-root country-states.json + country-cities.json exports of the Countries States
// Cities Database (ODbL-1.0). The 26 MB city export is split per country so a page loads only the chosen
// country's list. The source exports are not kept in the repository: download them from
// https://github.com/dr5hn/countries-states-cities-database (release noted in public/regions/NOTICE.md),
// place both files at the repository root, run  node scripts/generate-region-files.mjs  then delete them.
//
// Output per country (ISO 3166-1 alpha-2, upper case): { "states": [name, ...], "cities": [[name, stateIndex], ...] }
// States and cities are sorted by name; a city appears once per state.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const outDir = new URL("../public/regions/", import.meta.url);
const read = (name) => JSON.parse(readFileSync(new URL(name, root), "utf8"));
const statesExport = read("country-states.json");
const citiesExport = read("country-cities.json");
const byName = (a, b) => a.localeCompare(b, "en");

const citiesByCountry = new Map(citiesExport.countries.map((country) => [country.country_code, country.cities]));

mkdirSync(outDir, { recursive: true });
for (const file of readdirSync(outDir)) if (file.endsWith(".json")) rmSync(new URL(file, outDir));

let written = 0;
for (const country of statesExport.countries) {
  const code = country.country_code.toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) continue;
  const stateNames = new Map(country.states.map((state) => [state.state_id, state.state_name.trim()]));
  const cities = citiesByCountry.get(country.country_code) ?? [];
  for (const city of cities) if (!stateNames.has(city.state_id)) stateNames.set(city.state_id, city.state_name.trim());

  const states = [...new Set(stateNames.values())].filter(Boolean).sort(byName);
  if (states.length === 0) continue;
  const stateIndex = new Map(states.map((name, index) => [name, index]));
  const seen = new Set();
  const cityRows = [];
  for (const city of cities) {
    const name = city.city_name.trim();
    const index = stateIndex.get(stateNames.get(city.state_id));
    if (!name || index === undefined || seen.has(`${index}|${name}`)) continue;
    seen.add(`${index}|${name}`);
    cityRows.push([name, index]);
  }
  cityRows.sort((a, b) => byName(a[0], b[0]) || a[1] - b[1]);
  writeFileSync(new URL(`${code}.json`, outDir), JSON.stringify({ states, cities: cityRows }));
  written += 1;
}

const { metadata } = statesExport;
writeFileSync(
  new URL("NOTICE.md", outDir),
  `# Region data\n\nGenerated by \`frontend/scripts/generate-region-files.mjs\` — do not edit by hand.\n\nState/province and city names: ${metadata.source} (${metadata.source_url}), release ${metadata.release}, retrieved ${metadata.retrieved_at}. Licensed under ${metadata.license} (https://opendatacommons.org/licenses/odbl/1-0/).\n`,
);
console.log(`public/regions: ${written} countries`);
