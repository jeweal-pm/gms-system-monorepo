// Regenerates src/lib/flag-loaders.ts (company PhoneField flags, owner 2026-10-17 option A).
// Turbopack cannot resolve `import(\`country-flag-icons/string/3x2/${code}\`)`, so every phone country
// gets a literal import; each flag stays its own lazily loaded chunk. Run after upgrading
// libphonenumber-js or country-flag-icons:  node scripts/generate-flag-loaders.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { getCountries } = require("libphonenumber-js");
const flagExports = Object.keys(require("country-flag-icons/package.json").exports);

const codes = getCountries().filter((code) => flagExports.includes(`./string/3x2/${code}`)).sort();
const lines = codes.map((code) => `  ${code}: () => import("country-flag-icons/string/3x2/${code}"),`);
const source = `// Generated by scripts/generate-flag-loaders.mjs — do not edit by hand.
/** Lazy loaders for the PhoneField flags (country-flag-icons 3x2 SVG strings), one chunk per country. */
export const flagLoaders: Readonly<Record<string, () => Promise<{ default: string }>>> = {
${lines.join("\n")}
};
`;
writeFileSync(new URL("../src/lib/flag-loaders.ts", import.meta.url), source);
console.log(`flag-loaders.ts: ${codes.length} countries`);
